# Demonstrate commonly used string methods

text = " python programming "

print(text.upper())
print(text.lower())
print(text.title())
print(text.capitalize())
print(text.strip())
print(text.replace("python", "Java"))
print(text.find("program"))
print(text.count("m"))
print(text.startswith(" "))
print(text.endswith(" "))
