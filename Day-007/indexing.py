# Access tuple elements using indexing

colors = ("Red", "Green", "Blue", "Yellow", "Black")

print("Tuple:", colors)

print("\nPositive Indexing")
print("-----------------")
print(colors[0])
print(colors[2])
print(colors[4])

print("\nNegative Indexing")
print("-----------------")
print(colors[-1])
print(colors[-2])
