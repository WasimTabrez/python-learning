# Access list elements using positive and negative indexing

colors = ["Red", "Green", "Blue", "Yellow", "Black"]

print("Colors:", colors)

print("\nPositive Indexing")
print("-----------------")
print(f"First   : {colors[0]}")
print(f"Second  : {colors[1]}")
print(f"Last    : {colors[4]}")

print("\nNegative Indexing")
print("-----------------")
print(f"Last    : {colors[-1]}")
print(f"Second Last : {colors[-2]}")
